"""为什么这个游戏是「点一下走一格」，而不是 60 帧的真游戏。

这一页不用 `nac.*` 之外的东西，但它本身也是一次说明：在这个平台上，
"解释一件事"和"做一件事"的写法是一样的。
"""

import nac

nac.h1("为什么它是一格一格的")
nac.p("因为这一套东西里，一帧就是一次网络往返。")

nac.h2("现在的执行模型")
nac.table(
    ["环节", "现实"],
    [
        ["一次点击", "一次完整请求：表单提交 → 服务器 → 新的一页"],
        ["一页", "起一个新的 Python 进程，跑完就退出（约 80ms）"],
        ["一次响应", "一整页文字，最多 16KB"],
        ["服务端能主动推吗", "不能。只有请求-响应，没有推送"],
        ["客户端能跑页面给的代码吗", "不能。没有脚本引擎"],
    ],
)
nac.gap()
nac.p("所以「瞬时」这个词在这个平台上不存在：你点了，服务器才算一步，才算下一步。")

nac.h2("那为什么还能玩")
with nac.note("ok", "因为这一格一格的，正好是回合制的形状"):
    nac.p("拍一下 = 一个回合。回合之间世界不动，你可以慢慢想。")
    nac.p("这不是把实时游戏做残了，是换了一种玩法：节奏归玩家，不归时钟。")
nac.gap()
nac.p("顺带的好处：关掉窗口再回来，这一局还在 —— 因为状态根本不在客户端。")

nac.h2("画面是怎么来的")
nac.bullets(
    "没有图片、没有精灵图、没有 canvas。只有 [[scene]] 这块矩形画布。",
    "鸟是三块圆角矩形：身体、嘴、眼睛。水管是两根长条。",
    "天空和地面故意画得比画布大，四角落在画布外侧 —— 客户端的裁剪会把圆角吃掉。",
    "水管缺口那一端本来该是圆的，所以圆角矩形刚好当「管口」。",
)
nac.gap()
nac.p("换句话说：美术资源不是找来的，是「这个平台画得出来的东西」本身。")

nac.h2("如果要真做成实时的，缺什么")
nac.table(
    ["缺的东西", "要动哪里"],
    [
        ["页面可以持续输出帧", "协议：一个请求换一路流，而不是一页"],
        ["客户端按帧渲染", "客户端：把 `[[scene]]` 变成 60fps 的循环"],
        ["输入不必回服务器", "客户端：本地按键 → 本地状态 → 本地重绘"],
        ["状态要能只改一部分", "协议：局部更新，而不是整页替换"],
    ],
)
nac.gap()
with nac.note("warn", "这四条都会破坏现在的形状"):
    nac.p("每一条都不难，但它们合起来就是「浏览器 + 脚本引擎」。")
    nac.p("这个项目的选择是：宁可要「一次请求一页」的简单，不要那套东西。")

nac.gap()
nac.p(nac.inline_path("/play", "← 回去接着玩"), "　　", nac.inline_path("/", "回首页"))
